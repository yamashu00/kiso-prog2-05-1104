// 【まずやること】
//   ・「/* ここを書き換える */」の #define の行を書き換えて完成させる
//   ・完成の確認：3 と 4 を入力 →「3 + 4 = 7」「3 + 4 の2倍は14 です」と表示されればOK
//   ・2行目が 14 にならないときは、gcc -E 08-add.c で置き換わった式を確かめる
// 【やってみよう】
//   ① 2行目が14にならないマクロの書き方と、14になる書き方の違いを、ペアの人に説明する
// ==================================================
#include <stdio.h>
#define ADD(a, b) 0   /* ここを書き換える */

int main(void)
{
    int i1, i2;

    printf("整数1=");  scanf("%d", &i1);
    printf("整数2=");  scanf("%d", &i2);

    printf("%d + %d = %d\n", i1, i2, ADD(i1, i2));
    printf("%d + %d の2倍は%d です\n", i1, i2, ADD(i1, i2) * 2);
    return 0;
}
