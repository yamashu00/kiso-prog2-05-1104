// 【内容】バイト数をビット数に変換する関数形式マクロ BITS を定義して、プログラムを完成させる
// 【まずやること】
//   ・「/* ここを書き換える */」の #define の行を書き換えて完成させる
//   ・ヒント：1バイトは8ビット
//   ・完成の確認：4 を入力 →「4 バイトは32 ビットです」と表示されればOK
// 【やってみよう】
//   ① BITS(byte + 1) と書いても正しく計算されるか確かめる（カッコを付け忘れていないか）
// ==================================================
#include <stdio.h>
#define BITS(b) ((b) * 8)

int main(void)
{
    int byte;
    printf("整数=");
    scanf("%d", &byte);
    printf("%d バイトは%d ビットです\n", byte, BITS(byte));
    return 0;
}
