// ==================================================
// 【種類】作成（演習2・基本）
// 【内容】小文字を大文字に変換する関数形式マクロ UPPER を定義して、プログラムを完成させる
// 【まずやること】
//   ・「/* ここを書き換える */」の #define の行を書き換えて完成させる
//   ・ヒント：文字は数（文字コード）。'a' と 'A' の差を使う（1年で学んだASCIIコード）
//   ・完成の確認：a を入力 →「大文字に変換するとA です」、z →「Z」と表示されればOK
// 【やってみよう】
//   ① 大文字（例：B）を入力すると、どうなる？ 三項演算子を使って、小文字のときだけ変換するように直す
// ==================================================
#include <stdio.h>
#define UPPER(c) (c)   /* ここを書き換える */

int main(void)
{
    char c;
    printf("小文字を入力してください=");
    scanf("%c", &c);
    printf("大文字に変換すると%c です\n", UPPER(c));
    return 0;
}
